export function createSettingsTranslator(language: string) {
  const isEn = language === 'en';
  return function tr(ru: string, en?: string): string {
    if (!isEn) return ru;
    if (en) return en;
    return SETTINGS_TRANSLATIONS[ru] || ru;
  };
}
